#!/bin/sh
set -eu

# Values are read through awk's ENVIRON, never interpolated into shell, sed,
# JavaScript, or nginx source. Do not print public or private environment values.
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
asset_root=${KANEO_ASSET_ROOT:-/usr/share/nginx/html}
asset_include=${KANEO_ASSET_INCLUDE:-/etc/nginx/conf.d/kaneo-env-assets.inc}
changed_list=$(mktemp)
export KANEO_CHANGED_LIST="$changed_list" KANEO_ASSET_ROOT_DIR="$asset_root"
export KANEO_ENV_RENDERER="$script_dir/env.awk"

if [ -z "${KANEO_API_URL:-}" ]; then
  echo "WARNING: KANEO_API_URL is not set. API calls may fail." >&2
fi

# find -exec preserves spaces/newlines in filenames. Write each replacement
# beside its source before atomically replacing the complete file.
find "$asset_root" -type f -name '*.js' -exec sh -eu -c '
  for asset do
    # Only chunks that carry a placeholder are touched: the rest stay
    # byte-identical (awk would add a final newline) and cacheable for a year.
    grep -q KANEO_ "$asset" || continue
    temporary=$(mktemp "${asset}.XXXXXX")
    trap '\''rm -f "$temporary"'\'' EXIT HUP INT TERM
    LC_ALL=C awk -v mode=bundle -f "$KANEO_ENV_RENDERER" "$asset" > "$temporary"
    chmod 644 "$temporary"
    # A rewritten asset keeps its hashed name, so it must not be cached forever.
    cmp -s "$temporary" "$asset" || printf "%s\n" "${asset#"$KANEO_ASSET_ROOT_DIR"/}" >> "$KANEO_CHANGED_LIST"
    mv "$temporary" "$asset"
    trap - EXIT HUP INT TERM
  done
' sh {} +

# Serve JSON as static content. It must never become an nginx configuration
# string, where quotes, backslashes, and dollar signs have another meaning.
for mode in resource authorization; do
  target="$asset_root/mcp-oauth-$mode.json"
  temporary=$(mktemp "${target}.XXXXXX")
  trap 'rm -f "$temporary"' EXIT HUP INT TERM
  LC_ALL=C awk -v mode="$mode" -f "$KANEO_ENV_RENDERER" > "$temporary"
  chmod 644 "$temporary"
  mv "$temporary" "$target"
  trap - EXIT HUP INT TERM
done

# nginx include: exact locations that revalidate the rewritten assets. Only
# plain hashed asset names are written; anything else stays out of the config.
# On a restart of the same container the assets are already rewritten and
# nothing changes now: keep the names listed by the earlier run.
if [ -f "$asset_include" ]; then
  sed -n 's#^location = /\(assets/[A-Za-z0-9._-]*[.]js\) .*#\1#p' "$asset_include" >> "$changed_list"
fi
include_tmp=$(mktemp "${asset_include}.XXXXXX")
{
  echo "# Generated by env.sh: assets rewritten with runtime values revalidate."
  grep -E '^assets/[A-Za-z0-9._-]+[.]js$' "$changed_list" | sort -u | while IFS= read -r rel; do
    printf 'location = /%s { expires epoch; }\n' "$rel"
  done
} > "$include_tmp"
chmod 644 "$include_tmp"
mv "$include_tmp" "$asset_include"
rm -f "$changed_list"

echo "Public web configuration prepared."
