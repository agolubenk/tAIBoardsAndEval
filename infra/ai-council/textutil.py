#!/usr/bin/env python3
"""AI Council — общие текстовые примитивы. Только stdlib.

Пользователи: council.py (сравнение возражений между раундами спирали) и
learning.py (дедупликация предложений дрейфа рубрики). Общая причина: в обоих
местах сравниваются фразы, которые одна и та же модель пишет в разных словоформах
— «русский»/«русском», «языки»/«языках». Точное сравнение токенов такие пары не
сводит, а полноценный стеммер — внешняя зависимость, которой у подсистемы нет.

Поэтому обрезка по списку частых русских окончаний, а не морфологический разбор:
ложных слияний чуть больше, чем у настоящего стеммера, но при пороге Жаккара
0.55–0.6 это запас прочности, а не источник ошибок. Английские слова не трогаются.
"""
from __future__ import annotations

import re

# Порядок — от длинных к коротким: жадное снятие самого длинного окончания.
_RU_ENDINGS = (
    "иями", "ями", "ами", "его", "ого", "ему", "ому", "ыми", "ими",
    "ах", "ях", "ая", "яя", "ое", "ее", "ые", "ие", "ой", "ей", "ый", "ий",
    "ом", "ем", "ых", "их", "ую", "юю", "ов", "ев", "ья", "ье", "ью",
    "ы", "и", "е", "у", "ю", "а", "я", "о", "ь",
)


def _strip_ru_ending(word: str) -> str:
    if len(word) <= 4:
        return word
    for ending in _RU_ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= 3:
            return word[: -len(ending)]
    return word


def tokens(text: str) -> set[str]:
    """Значимые слова фразы: нижний регистр, слова ≤2 символов отброшены,
    русские окончания обрезаны. Цифры сохраняются (429 в «429 hh.ru» — смысловое)."""
    return {_strip_ru_ending(raw)
            for raw in re.split(r"[^0-9a-zа-яё]+", (text or "").lower())
            if len(raw) > 2}


# ── языковая дисциплина (RU/EN) ─────────────────────────────────────────────
# Правило «весь текст на русском, идентификаторы на английском» есть в каждом
# промпте со времён первых предложений дрейфа рубрики — и всё равно ответы
# приезжают с украинским, казахским и китайским (замер 2026-10-15: 76 из 724
# успешных ответов за 14 дней — «DRY原则», «遗漏或», «Логіка під»). Промпт не механизм:
# детектор ниже — детерминированный, он ловит то, что модель продолжает нарушать.
# Латиница НЕ проверяется: отличить английские слова от, скажем, польских
# без словаря нельзя, а такие вставки в этом консилиуме не встречались.
#
# Ложные срабатывания, которых детектор избегает (GLM-ревью #155):
# - греческие буквы формул («порог Δ=0.20», «α=0.05») — греческий считается только словом от 3 букв;
# - иконки шрифтов (приватная зона Unicode) — не язык, не проверяются;
# - одна буква/имя собственное («Мінск») — чужая кириллица считается от двух слов;
# - цитата из постановки — слова из `allowed` (текст карточки) не нарушение.
_FOREIGN_SCRIPT_RE = re.compile(
    "[\u0590-\u05FF"     # иврит
    "\u0600-\u06FF"      # арабский
    "\u0900-\u097F"      # деванагари
    "\u3040-\u30FF"      # кана
    "\u3400-\u4DBF\u4E00-\u9FFF\uF900-\uFAFF"  # CJK
    "\uAC00-\uD7AF"      # хангыл
    "]+"
)
_GREEK_WORD_RE = re.compile("[\u0370-\u03FF]{3,}")
# Слово кириллицей, в котором есть буква вне русского алфавита: украинская (ї є ґ і),
# казахская (ә ғ қ ң ө ұ ү һ), белорусская (ў), сербская (ђ ћ џ)…
_CYRILLIC_WORD_RE = re.compile("[\u0400-\u04FF]+")
_RU_LETTERS = frozenset("абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ")
_FOREIGN_CYRILLIC_MIN_WORDS = 2


def _context(text: str, start: int, end: int) -> str:
    return text[max(start - 6, 0):end + 6].strip()


def foreign_script_samples(text: str, limit: int = 5, allowed: str = "") -> list[str]:
    """Фрагменты текста на недопустимом языке/письменности (для диагностики).

    Пустой список = нарушений нет. Возвращает фрагмент с коротким контекстом,
    чтобы лог ретрая объяснял, ЧТО именно было не так, а не просто «язык».
    `allowed` — текст постановки: слова, процитированные из неё, нарушением не считаются.
    """
    text = text or ""
    allowed_words = set(_CYRILLIC_WORD_RE.findall((allowed or "").lower()))
    samples: list[str] = []
    for m in _FOREIGN_SCRIPT_RE.finditer(text):
        if m.group(0) not in (allowed or ""):
            samples.append(_context(text, m.start(), m.end()))
    for m in _GREEK_WORD_RE.finditer(text):
        if m.group(0) not in (allowed or ""):
            samples.append(_context(text, m.start(), m.end()))
    cyrillic = [m for m in _CYRILLIC_WORD_RE.finditer(text)
                if not set(m.group(0)) <= _RU_LETTERS and m.group(0).lower() not in allowed_words]
    if len(cyrillic) >= _FOREIGN_CYRILLIC_MIN_WORDS:
        samples.extend(_context(text, m.start(), m.end()) for m in cyrillic)
    return samples[:limit]


def has_foreign_script(text: str, allowed: str = "") -> bool:
    """True, если текст содержит письменность/слова вне русского и английского.

    Детерминированный гейт языковой политики: тот же смысл, что правило в промптах,
    но его нельзя проигнорировать. Идентификаторы кода (латиница) не задевает.
    """
    return bool(foreign_script_samples(text, limit=1, allowed=allowed))
