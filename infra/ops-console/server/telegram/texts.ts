/** owner@company.com → o***@company.com — подтвердить «это моя учётка», не раскрывая её целиком. */
export function maskEmail(email: string): string {
  const [name = '', domain = ''] = email.split('@')
  return `${name.slice(0, 1)}***@${domain}`
}

